-- Track the embedding wire format separately from the model alias. The same
-- LiteLLM alias previously returned binary 0/1 vectors when encoding_format
-- was omitted, so model name and dimension alone cannot prove compatibility.
-- Existing unlabelled vectors are derived data and are cleared for safe float
-- regeneration. Chunk text, hashes, identifiers, and source relationships are
-- preserved.

BEGIN;

SET LOCAL search_path = pg_catalog, public;

ALTER TABLE public.policy_chunk
    ADD COLUMN IF NOT EXISTS embedding_encoding_format VARCHAR(20);

ALTER TABLE public.policy_web_chunk
    ADD COLUMN IF NOT EXISTS embedding_encoding_format VARCHAR(20);

ALTER TABLE public.rag_retrieval_chunk
    ADD COLUMN IF NOT EXISTS embedding_encoding_format VARCHAR(20);

-- An unlabelled vector cannot safely be assumed to be float. This update is
-- idempotent: vectors regenerated by the new ETL are labelled 'float' and are
-- left untouched if the migration is rerun.
UPDATE public.policy_chunk
SET embedding = NULL,
    embedding_model = NULL,
    embedding_encoding_format = NULL,
    token_count = NULL,
    embedded_at = NULL,
    embedding_error = NULL
WHERE embedding IS NOT NULL
  AND embedding_encoding_format IS NULL;

UPDATE public.policy_web_chunk
SET embedding = NULL,
    embedding_model = NULL,
    embedding_encoding_format = NULL,
    token_count = NULL,
    embedded_at = NULL,
    embedding_error = NULL,
    updated_at = NOW()
WHERE embedding IS NOT NULL
  AND embedding_encoding_format IS NULL;

-- The unified retrieval table is a disposable projection. Remove old rows
-- instead of retaining vectors whose wire format is unknown.
DELETE FROM public.rag_retrieval_chunk
WHERE embedding_encoding_format IS NULL;

ALTER TABLE public.policy_chunk
    DROP CONSTRAINT IF EXISTS chk_policy_chunk_embedding_state;

ALTER TABLE public.policy_chunk
    ADD CONSTRAINT chk_policy_chunk_embedding_state
    CHECK (
        (
            embedding IS NULL
            AND embedding_model IS NULL
            AND embedding_encoding_format IS NULL
            AND embedded_at IS NULL
        )
        OR
        (
            embedding IS NOT NULL
            AND embedding_model IS NOT NULL
            AND BTRIM(embedding_model) <> ''
            AND embedding_encoding_format = 'float'
            AND embedded_at IS NOT NULL
            AND embedding_error IS NULL
        )
    );

ALTER TABLE public.policy_web_chunk
    DROP CONSTRAINT IF EXISTS chk_policy_web_chunk_embedding_state;

ALTER TABLE public.policy_web_chunk
    ADD CONSTRAINT chk_policy_web_chunk_embedding_state
    CHECK (
        (
            embedding IS NULL
            AND embedding_model IS NULL
            AND embedding_encoding_format IS NULL
            AND embedded_at IS NULL
        )
        OR
        (
            embedding IS NOT NULL
            AND embedding_model IS NOT NULL
            AND BTRIM(embedding_model) <> ''
            AND embedding_encoding_format = 'float'
            AND embedded_at IS NOT NULL
            AND embedding_error IS NULL
        )
    );

ALTER TABLE public.rag_retrieval_chunk
    ALTER COLUMN embedding_encoding_format SET NOT NULL;

ALTER TABLE public.rag_retrieval_chunk
    DROP CONSTRAINT IF EXISTS chk_rag_retrieval_chunk_encoding_format;

ALTER TABLE public.rag_retrieval_chunk
    ADD CONSTRAINT chk_rag_retrieval_chunk_encoding_format
    CHECK (embedding_encoding_format = 'float');

CREATE OR REPLACE VIEW public.v_verified_policy_web_chunk AS
SELECT
    chunk.web_chunk_id,
    chunk.policy_no,
    chunk.document_id,
    document.source_id,
    'CRAWLED_WEB'::TEXT AS source_type,
    source.canonical_url,
    source.final_url,
    document.title AS document_title,
    document.fetched_at,
    chunk.chunk_index,
    chunk.chunk_type,
    chunk.heading,
    chunk.content,
    chunk.content_hash,
    chunk.chunker_version,
    chunk.embedding,
    chunk.embedding_model,
    chunk.token_count,
    chunk.embedded_at,
    chunk.created_at,
    chunk.updated_at,
    chunk.embedding_encoding_format
FROM public.policy_web_chunk AS chunk
JOIN public.policy AS policy_row
  ON policy_row.policy_no = chunk.policy_no
JOIN public.web_document AS document
  ON document.document_id = chunk.document_id
JOIN public.web_source AS source
  ON source.source_id = document.source_id
WHERE policy_row.is_active = TRUE
  AND document.is_current = TRUE
  AND EXISTS (
      SELECT 1
      FROM public.policy_web_source AS link
      WHERE link.policy_no = chunk.policy_no
        AND link.source_id = document.source_id
        AND link.is_active = TRUE
        AND link.validation_status = 'VERIFIED'
        AND link.validated_document_id = document.document_id
  );

COMMENT ON COLUMN public.policy_chunk.embedding_encoding_format IS
    'OpenAI-compatible embedding response format; only float is retrievable.';

COMMENT ON COLUMN public.policy_web_chunk.embedding_encoding_format IS
    'OpenAI-compatible embedding response format; only float is retrievable.';

COMMENT ON COLUMN public.rag_retrieval_chunk.embedding_encoding_format IS
    'Copied embedding response format; constrained to float.';

COMMIT;
